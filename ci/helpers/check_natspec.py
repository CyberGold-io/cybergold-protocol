#!/usr/bin/env python3
"""Validate NatSpec completeness from Foundry AST artifacts."""

from __future__ import annotations

import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any


SUMMARY_TAGS = {"notice", "dev", "inheritdoc", "title"}
BAD_TEXT_PATTERNS = [
    re.compile(r"\bTODO\b", re.IGNORECASE),
    re.compile(r"\bTBD\b", re.IGNORECASE),
    re.compile(r"\bFIXME\b", re.IGNORECASE),
    re.compile(r"fields for this package flow", re.IGNORECASE),
    re.compile(r"return value produced by the documented view", re.IGNORECASE),
    re.compile(r"deployment artifacts, JSON payload, or encoded bytes produced by the helper", re.IGNORECASE),
    re.compile(r"storage pointer for the requested storage namespace", re.IGNORECASE),
    re.compile(r"downcast uint(?:64|128|256) value", re.IGNORECASE),
    re.compile(r"configured pPM", re.IGNORECASE),
]
TAG_RE = re.compile(r"^@([A-Za-z][A-Za-z0-9_-]*)(?:\s+(.*))?$")
GENERATED_MARKER = "@generated by script/generate-release-abi.py"


@dataclass(frozen=True)
class Tag:
    name: str
    arg: str
    desc: str


@dataclass(frozen=True)
class Issue:
    path: str
    line: int
    label: str
    message: str

    def format(self) -> str:
        return f"{self.path}:{self.line}: {self.label}: {self.message}"


class Checker:
    def __init__(self, root: Path, source_prefixes: list[str]) -> None:
        self.root = root.resolve()
        configured_out = Path(os.environ.get("FOUNDRY_OUT", "out"))
        self.out_dir = configured_out if configured_out.is_absolute() else self.root / configured_out
        self.source_prefixes = tuple(prefix.rstrip("/") + "/" for prefix in source_prefixes)
        self.issues: list[Issue] = []
        self.sources_seen: set[str] = set()
        self.line_cache: dict[str, list[int]] = {}

    def run(self) -> int:
        for artifact in sorted(self.out_dir.rglob("*.json")):
            self._check_artifact(artifact)

        expected_sources = {
            source.relative_to(self.root).as_posix()
            for prefix in self.source_prefixes
            for source in (self.root / prefix).rglob("*.sol")
            if GENERATED_MARKER not in source.read_text(errors="ignore")
        }
        for source in sorted(expected_sources - self.sources_seen):
            self._issue(source, 1, "source", "no AST artifact found after forge build --ast")

        if not expected_sources:
            print("No Solidity source files found in configured NatSpec scope.", file=sys.stderr)
            return 1

        if self.issues:
            for issue in sorted(self.issues, key=lambda item: (item.path, item.line, item.label, item.message)):
                print(issue.format(), file=sys.stderr)
            print(f"NatSpec check failed with {len(self.issues)} issue(s).", file=sys.stderr)
            return 1

        print(f"NatSpec check passed for {len(expected_sources)} Solidity source file(s).")
        return 0

    def _check_artifact(self, artifact: Path) -> None:
        try:
            data = json.loads(artifact.read_text())
        except (OSError, json.JSONDecodeError):
            return

        ast = data.get("ast")
        if not isinstance(ast, dict):
            return

        source_path = self._normalize_source_path(ast.get("absolutePath"))
        if source_path is None or source_path in self.sources_seen:
            return

        self.sources_seen.add(source_path)
        self._check_source_unit(source_path, ast)

    def _normalize_source_path(self, raw_path: Any) -> str | None:
        if not isinstance(raw_path, str) or not raw_path:
            return None

        path = Path(raw_path)
        if path.is_absolute():
            try:
                rel_path = path.resolve().relative_to(self.root).as_posix()
            except ValueError:
                return None
        else:
            rel_path = path.as_posix()

        if not rel_path.endswith(".sol"):
            return None
        if not rel_path.startswith(self.source_prefixes):
            return None
        if GENERATED_MARKER in (self.root / rel_path).read_text(errors="ignore"):
            return None
        return rel_path

    def _check_source_unit(self, source_path: str, ast: dict[str, Any]) -> None:
        for node in ast.get("nodes", []):
            self._check_node(source_path, node, None)

    def _check_node(self, source_path: str, node: dict[str, Any], parent: str | None) -> None:
        node_type = node.get("nodeType")
        if node_type == "ContractDefinition":
            label = f"{node.get('contractKind', 'contract')} {node.get('name', '<unnamed>')}"
            self._require_doc(source_path, node, label)
            for child in node.get("nodes", []):
                self._check_node(source_path, child, label)
            return

        if node_type == "FunctionDefinition":
            self._check_function(source_path, node)
            return

        if node_type == "VariableDeclaration" and node.get("stateVariable") and node.get("visibility") == "public":
            self._require_doc(source_path, node, f"public state variable {node.get('name', '<unnamed>')}")
            return

        if node_type == "EventDefinition":
            label = f"event {node.get('name', '<unnamed>')}"
            tags = self._require_doc(source_path, node, label)
            self._require_param_tags(source_path, node, label, tags, self._parameters(node))
            return

        if node_type == "ErrorDefinition":
            label = f"error {node.get('name', '<unnamed>')}"
            tags = self._require_doc(source_path, node, label)
            self._require_param_tags(source_path, node, label, tags, self._parameters(node))
            return

        if node_type == "StructDefinition":
            label = f"struct {node.get('name', '<unnamed>')}"
            self._require_doc(source_path, node, label)
            return

        if node_type == "EnumDefinition":
            self._require_doc(source_path, node, f"enum {node.get('name', '<unnamed>')}")
            return

        if isinstance(node.get("nodes"), list):
            for child in node["nodes"]:
                self._check_node(source_path, child, parent)

    def _check_function(self, source_path: str, node: dict[str, Any]) -> None:
        if node.get("visibility") not in {"public", "external"}:
            return
        kind = node.get("kind", "function")
        name = node.get("name") or kind
        label = f"{kind} {name}" if kind != "function" else f"function {name}"
        tags = self._require_doc(source_path, node, label)
        self._require_param_tags(source_path, node, label, tags, self._parameters(node))
        self._require_return_tags(source_path, node, label, tags, self._return_parameters(node))

    def _require_doc(self, source_path: str, node: dict[str, Any], label: str) -> list[Tag]:
        text = self._doc_text(node)
        line = self._line(source_path, node)
        if not text:
            self._issue(source_path, line, label, "missing NatSpec documentation")
            return []

        for pattern in BAD_TEXT_PATTERNS:
            if pattern.search(text):
                self._issue(source_path, line, label, "NatSpec contains placeholder text")
                break

        tags = self._parse_tags(text)
        if not any(tag.name in SUMMARY_TAGS and self._meaningful(tag) for tag in tags):
            self._issue(source_path, line, label, "missing @notice, @dev, @inheritdoc, or @title summary")

        return tags

    def _require_param_tags(
        self,
        source_path: str,
        node: dict[str, Any],
        label: str,
        tags: list[Tag],
        params: list[dict[str, Any]],
    ) -> None:
        if self._has_inheritdoc(tags):
            return

        param_docs = {tag.arg: tag for tag in tags if tag.name == "param" and tag.arg}
        for param in params:
            name = param.get("name")
            if not name:
                continue
            tag = param_docs.get(name)
            if tag is None:
                self._issue(
                    source_path,
                    self._line(source_path, param),
                    label,
                    f"missing @param documentation for `{name}`",
                )
            elif not self._meaningful(tag):
                self._issue(
                    source_path,
                    self._line(source_path, param),
                    label,
                    f"empty @param documentation for `{name}`",
                )

    def _require_return_tags(
        self,
        source_path: str,
        node: dict[str, Any],
        label: str,
        tags: list[Tag],
        returns: list[dict[str, Any]],
    ) -> None:
        if not returns or self._has_inheritdoc(tags):
            return

        return_tags = [tag for tag in tags if tag.name == "return"]
        named_returns = [param for param in returns if param.get("name")]
        if named_returns:
            return_docs = {tag.arg: tag for tag in return_tags if tag.arg}
            for param in named_returns:
                name = param["name"]
                tag = return_docs.get(name)
                if tag is None:
                    self._issue(
                        source_path,
                        self._line(source_path, param),
                        label,
                        f"missing @return documentation for `{name}`",
                    )
                elif not self._meaningful(tag):
                    self._issue(
                        source_path,
                        self._line(source_path, param),
                        label,
                        f"empty @return documentation for `{name}`",
                    )
            return

        if len(return_tags) < len(returns):
            self._issue(
                source_path,
                self._line(source_path, node),
                label,
                f"missing @return documentation for {len(returns) - len(return_tags)} return value(s)",
            )
            return

        for tag in return_tags[: len(returns)]:
            if not self._meaningful(tag):
                self._issue(source_path, self._line(source_path, node), label, "empty @return documentation")

    def _parameters(self, node: dict[str, Any]) -> list[dict[str, Any]]:
        params = node.get("parameters", {}).get("parameters", [])
        return params if isinstance(params, list) else []

    def _return_parameters(self, node: dict[str, Any]) -> list[dict[str, Any]]:
        params = node.get("returnParameters", {}).get("parameters", [])
        return params if isinstance(params, list) else []

    def _has_inheritdoc(self, tags: list[Tag]) -> bool:
        return any(tag.name == "inheritdoc" for tag in tags)

    def _meaningful(self, tag: Tag) -> bool:
        return bool((tag.desc or tag.arg).strip())

    def _doc_text(self, node: dict[str, Any]) -> str:
        doc = node.get("documentation")
        if isinstance(doc, str):
            return doc.strip()
        if isinstance(doc, dict) and isinstance(doc.get("text"), str):
            return doc["text"].strip()
        return ""

    def _parse_tags(self, text: str) -> list[Tag]:
        tags: list[dict[str, str]] = []
        current: dict[str, str] | None = None

        for raw_line in text.splitlines():
            line = raw_line.strip()
            if line.startswith("*"):
                line = line[1:].strip()
            if not line:
                continue

            match = TAG_RE.match(line)
            if match:
                name = match.group(1)
                rest = (match.group(2) or "").strip()
                arg = ""
                desc = rest
                if name in {"param", "return"}:
                    parts = rest.split(None, 1)
                    arg = parts[0] if parts else ""
                    desc = parts[1] if len(parts) > 1 else ""
                current = {"name": name, "arg": arg, "desc": desc}
                tags.append(current)
            elif current is not None:
                current["desc"] = (current["desc"] + "\n" + line).strip()

        return [Tag(tag["name"], tag["arg"], tag["desc"]) for tag in tags]

    def _line(self, source_path: str, node: dict[str, Any]) -> int:
        src = node.get("src", "")
        try:
            start = int(str(src).split(":", 1)[0])
        except ValueError:
            return 1
        if start < 0:
            return 1

        offsets = self.line_cache.get(source_path)
        if offsets is None:
            try:
                text = (self.root / source_path).read_text()
            except OSError:
                return 1
            offsets = [0]
            offsets.extend(match.end() for match in re.finditer("\n", text))
            self.line_cache[source_path] = offsets

        line = 1
        for index, offset in enumerate(offsets):
            if offset > start:
                break
            line = index + 1
        return line

    def _issue(self, source_path: str, line: int, label: str, message: str) -> None:
        self.issues.append(Issue(source_path, line, label, message))


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: check_natspec.py <root> <source-prefix> [<source-prefix> ...]", file=sys.stderr)
        return 2

    root = Path(sys.argv[1])
    source_prefixes = sys.argv[2:]
    return Checker(root, source_prefixes).run()


if __name__ == "__main__":
    raise SystemExit(main())
